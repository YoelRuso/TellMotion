#!/usr/bin/env node
// Usage: node tools/apply-theme.mjs <theme-id | path/to/theme.json> <projectDir>
// Writes <projectDir>/src/theme.ts and src/fonts.ts, and adds the @fontsource dependency to package.json.
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {loadTheme, validateTheme} from './lib/theme.mjs';

const [idArg, dir] = process.argv.slice(2);
if (!idArg || !dir) {
  console.error('Usage: apply-theme.mjs <theme-id|theme.json> <projectDir>');
  process.exit(1);
}
const theme = loadTheme(idArg);
const errs = validateTheme(theme);
if (errs.length) {
  console.error('Invalid theme:\n - ' + errs.join('\n - '));
  process.exit(1);
}

const {prompt, description, ...runtime} = theme; // keep runtime tokens only
writeFileSync(
  join(dir, 'src', 'theme.ts'),
  `// GENERATED by tools/apply-theme.mjs from theme "${theme.id}". Do not edit by hand: change the theme and re-apply.\n` +
    `import type {ThemeTokens} from './theme-types';\n\nexport const THEME: ThemeTokens = ${JSON.stringify(runtime, null, 2)};\n`,
);

const weights = [...new Set([400, theme.fonts.weights.find(w => w >= 700) ?? theme.fonts.weights.at(-1)])];
writeFileSync(
  join(dir, 'src', 'fonts.ts'),
  `// GENERATED by tools/apply-theme.mjs\n` + weights.map(w => `import '@fontsource/${theme.fonts.fontsource}/${w}.css';`).join('\n') + '\n',
);

const pkgPath = join(dir, 'package.json');
if (existsSync(pkgPath)) {
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  for (const k of Object.keys(pkg.dependencies || {})) if (k.startsWith('@fontsource/')) delete pkg.dependencies[k];
  pkg.dependencies[`@fontsource/${theme.fonts.fontsource}`] = '^5.0.0';
  pkg.dependencies = Object.fromEntries(Object.entries(pkg.dependencies).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
}
console.log(`✓ Theme "${theme.name}" applied to ${dir} (run npm install if the font package changed)`);
